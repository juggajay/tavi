import "../isolate.js";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { DatabaseSync } from "node:sqlite";
import { db, MIGRATIONS } from "../../src/store/db.js";
import { appendRow, changedSince, dropRow, latestGeneration, rewriteRow, rowsOf } from "../../src/hq/rows.js";

assert.equal(MIGRATIONS.length >= 20 && MIGRATIONS[19].includes("CREATE TABLE bot_rows"), true, "the conversation rows are migration 20");
assert.equal(createHash("sha256").update(MIGRATIONS.slice(0, 15).join("\u0000")).digest("hex"), "fcd9ab350c8bf6ae8a394e9730925cddd3345c2a089f3d84c122afdf23583c2d", "the reviewed earlier migration text stays pinned");
const older = new DatabaseSync(":memory:");
try {
  for (const step of MIGRATIONS.slice(0, 18)) older.exec(step);
  older.prepare("INSERT INTO settings(key, value) VALUES ('existing', 'keep this')").run();
  for (const step of MIGRATIONS.slice(18)) older.exec(step);
  assert.equal((older.prepare("SELECT value FROM settings WHERE key = 'existing'").get() as { value: string }).value, "keep this");
  const table = (database: DatabaseSync) => database.prepare("SELECT name, sql FROM sqlite_master WHERE name IN ('bot_rows', 'bot_rows_rev') ORDER BY name").all();
  assert.deepEqual(table(older), table(db), "an older database gains the same conversation table and index as a fresh one");
} finally { older.close(); }
const a = appendRow("one", 1, { kind: "message", from: "owner", text: "Hello" });
const b = appendRow("one", 1, { kind: "message", from: "bot", text: "First", streaming: true });
const c = rewriteRow("one", 1, b.seq, { kind: "message", from: "bot", text: "Finished", streaming: false });
assert.equal(c.seq, b.seq);
assert.ok(c.rev > b.rev);
assert.equal(c.ts, b.ts);
assert.equal(rowsOf("one", 1).length, 2);
assert.deepEqual(changedSince("one", b.rev), [c]);
assert.deepEqual(rowsOf("one", 1, { afterSeq: a.seq, limit: 1 }), [c]);
assert.deepEqual(rowsOf("one", 1, { limit: 0 }), []);
assert.equal(latestGeneration("missing"), 0);
const newer = appendRow("one", 2, { kind: "notice", text: "A fresh conversation", tone: "info" });
assert.equal(newer.seq, 1);
assert.ok(newer.rev > c.rev);
assert.equal(latestGeneration("one"), 2);
assert.equal(appendRow("two", 1, { kind: "notice", text: "Hello", tone: "info" }).rev, 1);
const removed = dropRow("one", 2, newer.seq)!;
assert.ok(removed.rev > newer.rev);
assert.equal(dropRow("one", 2, newer.seq), null);
const again = appendRow("one", 2, { kind: "notice", text: "Later", tone: "info" });
assert.ok(again.rev > removed.rev);
assert.ok(again.seq > newer.seq, "a removed position is never used again");
assert.throws(() => rewriteRow("one", 2, 900, { kind: "notice", text: "Missing", tone: "info" }), /could not be found/);

const before = db.prepare("SELECT COUNT(*) n FROM bot_rows").get();
const settings = db.prepare("SELECT COUNT(*) n FROM settings").get();
const options = { test: true, scope: "practice" };
const testRow = appendRow("one", 20, { kind: "message", from: "bot", text: "Practice" }, options);
const separate = appendRow("one", 20, { kind: "message", from: "bot", text: "Another practice" }, { test: true, scope: "separate" });
assert.ok(separate.rev > testRow.rev, "one change counter covers this bot's practice conversations too");
const testRewritten = rewriteRow("one", 20, testRow.seq, { kind: "message", from: "bot", text: "Changed" }, options);
assert.deepEqual(rowsOf("one", 20, options), [testRewritten]);
assert.deepEqual(changedSince("one", testRow.rev, options), [testRewritten]);
assert.equal(latestGeneration("one", options), 20);
assert.equal(latestGeneration("one"), 2);
assert.deepEqual(rowsOf("one", 20, { test: true, scope: "another practice" }), []);
testRewritten.body = { kind: "notice", tone: "warn", text: "Caller changed its copy" };
assert.equal(rowsOf("one", 20, options)[0].kind, "message");
dropRow("one", 20, testRow.seq, options);
assert.deepEqual(rowsOf("one", 20, options), []);
assert.deepEqual(db.prepare("SELECT COUNT(*) n FROM bot_rows").get(), before);
assert.deepEqual(db.prepare("SELECT COUNT(*) n FROM settings").get(), settings);
console.log("hq-rows: ok");
