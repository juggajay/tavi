import "../isolate.js";
import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import { db, MIGRATIONS } from "../../src/store/db.js";
import { createBot, getBot, seedTeam } from "../../src/hq/bots.js";
import { CARD_SERVERS, cardHistory, cardWarnings, currentCard, dangerousThree, renderCard, restoreCard, saveCard, validateCard, type JobCard } from "../../src/hq/cards/index.js";
import { fakeAccountProtection } from "../fake-hermes.js";

fakeAccountProtection();
const seeded = seedTeam();
assert.deepEqual(currentCard(seeded[0].id)?.servers, [...CARD_SERVERS]);
assert.notEqual(currentCard(seeded[0].id)?.privateInfo, "named");
const card: JobCard = { version: 1, purpose: "Compare travel options", notFor: "Booking or paying", handsBack: "A short comparison with sources", example: null, given: "Places and dates", servers: ["calc", "show"], stopAndAsk: "When dates or budget are missing", choice: { provider: "anthropic", model: "test-model" }, fallbacks: [], computer: false, trials: [{ ask: "Compare two short trips", goodAnswer: "Two choices with clear costs" }], privateInfo: "none" };
assert.deepEqual(validateCard(card), card);
assert.ok(cardWarnings(card).some((s) => s.includes("No example")));
assert.ok(cardWarnings({ ...card, trials: [] }).some((s) => s.includes("No trial")));
assert.ok(renderCard(card).includes(card.purpose));
for (const patch of [{ purpose: " " }, { servers: ["missing"] }, { servers: ["calc", "calc"] }, { choice: { provider: "anthropic", model: "" } }, { version: 0 }, { privateInfo: "named" }, { named: ["secret"] }, { unexpected: "words" }]) assert.throws(() => validateCard({ ...card, ...patch }));
const risky: JobCard = { ...card, servers: ["mail", "actions"], privateInfo: "named", named: ["Travel budget"] };
assert.ok(dangerousThree(risky));
assert.throws(() => validateCard(risky), /Drop outside reading/);
assert.throws(() => validateCard({ ...risky, acknowledgedRisk: true }), /job card/);
assert.deepEqual(validateCard(risky, { acknowledgedRisk: true }), risky);
for (const safe of [{ ...risky, privateInfo: "about-card" as const, named: undefined }, { ...risky, servers: ["calc"] }]) assert.ok(validateCard(safe));
const bot = createBot({ id: "travel", name: "Travel", card });
assert.equal(bot.card?.version, 1);
assert.ok((getBot(bot.id)!.servers as string[]).includes("team"));
saveCard(bot.id, { ...card, version: 99, purpose: "Compare rail trips" }, "owner", "Focus on trains.");
assert.equal(currentCard(bot.id)?.version, 2);
assert.equal(cardHistory(bot.id)[0].madeBy, "owner");
assert.equal(cardHistory(bot.id)[1].card.purpose, card.purpose);
restoreCard(bot.id, 1);
assert.equal(currentCard(bot.id)?.version, 3);
assert.equal(currentCard(bot.id)?.purpose, card.purpose);
assert.equal(cardHistory(bot.id).length, 3);
assert.throws(() => restoreCard(bot.id, 30), /could not be found/);
assert.throws(() => saveCard("absent", card, "owner", "Test"), /no longer/);
assert.throws(() => saveCard(bot.id, risky, "bot", "Test"), /owner's tap/);
saveCard(bot.id, risky, "owner", "Approved all three.", { acknowledgedRisk: true });
restoreCard(bot.id, 4);
assert.equal(cardHistory(bot.id)[0].acknowledgedRisk, true);
assert.equal(card.version, 1);

const older = new DatabaseSync(":memory:");
for (const migration of MIGRATIONS.slice(0, 20)) older.exec(migration);
older.prepare("INSERT INTO memories(id,kind,subject,fact,status,created_at,updated_at) VALUES('old','user','Owner','A kept fact','active','now','now')").run();
older.exec(MIGRATIONS[20]);
assert.equal((older.prepare("SELECT scope FROM memories").get() as { scope: string }).scope, "lead");
assert.equal((older.prepare("SELECT text FROM about_card").get() as { text: string }).text, "");
older.close();
assert.equal((db.prepare("PRAGMA user_version").get() as { user_version: number }).user_version, 21);
console.log("job cards: checks, versions, putting back an old card, risky combinations and older notebooks pass");
