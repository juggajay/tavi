import "../isolate.js";
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { buildSystemPrompt, CORE, WALLS, DRAWING_RULES, FILE_RULES, REFERENCE_RULES, GUIDE_RULES, SIZE_RULES, MODEL_RULES, SHOP_RULES, COMPUTER_RULES } from "../../src/brain/rules.js";
import { SOURCE_RULES } from "../../src/brain/sourceRules.js";
import { BRAINLINK_RULES } from "../../src/brainlink/rules.js";
import { readSoul, readUser } from "../../src/profile/profile.js";
import { createBot, updateBot } from "../../src/hq/bots.js";
import { buildBotPrompt, soulFor, standingFor } from "../../src/hq/engines/standing.js";
import { fakeAccountProtection } from "../fake-hermes.js";

fakeAccountProtection();
// Pin the general instructions after the wording cleanup; tool and permission coverage is checked below.
const hash = () => createHash("sha256").update(buildSystemPrompt("Test soul.", "Test user.", "Pebble")).digest("hex");
const before = "0f5560c3f03c5f5a87d47ab30f3e9eb204ddf80a90610d2019b64bd4bc7a6045";
assert.equal(hash(), before);
const bot = createBot({ id: "first", name: "First", role: "Check the work", soul: "Owner's extra words." });
createBot({ id: "second", name: "Second", role: "A second opinion" });
const short = soulFor(bot);
assert.ok(short.includes("You are First"));
assert.ok(short.includes("Second: A second opinion"));
assert.ok(short.includes("owner is the boss"));
assert.ok(short.includes("Your tools and your walls"));
assert.ok(!short.includes(CORE));
assert.ok(!short.includes(bot.soul));
assert.ok(short.length < 20000);
const full = standingFor(bot);
for (const rule of [CORE, WALLS, DRAWING_RULES, FILE_RULES, REFERENCE_RULES, GUIDE_RULES, SIZE_RULES, SOURCE_RULES, MODEL_RULES, SHOP_RULES, COMPUTER_RULES, BRAINLINK_RULES]) assert.ok(full.includes(rule));
assert.ok(full.includes(readSoul().trim()));
assert.ok(full.includes(readUser().trim()));
assert.ok(full.startsWith(short + "\n\n"));
assert.ok(full.endsWith(bot.soul));
assert.ok(full.length > 20000);
assert.ok(!full.includes('- "spoken":'));
assert.ok(!full.includes('- "card":'));
assert.ok(!full.includes("call set_my_name"));
assert.ok(!full.includes("call start_work first"));
assert.ok(!full.includes("A separate voice model"));
assert.ok(!full.includes("WebSearch"));
assert.ok(full.includes("show_list"));
assert.ok(full.includes("request_action"));
assert.ok(full.includes("share brief progress"));
const long = updateBot(bot.id, { soul: "Extra words. ".repeat(4000) });
assert.ok(standingFor(long).endsWith(long.soul));
assert.equal(soulFor(long), short);
assert.ok(buildBotPrompt("Named soul", "Named user", "First").includes("Named user"));
assert.equal(hash(), before);
console.log("bot standing instructions: ok");
